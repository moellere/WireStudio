"""Parametric OpenSCAD enclosure, built on YAPP_Box.

Reads the board's `enclosure:` metadata (PCB outline, mount holes,
ports) and emits a self-contained `.scad` file: the studio's tunables,
the pinned YAPP_Box generator (MIT, vendored in `yapp/`), and the YAPP
parameters derived from both. YAPP lays out the base and the lid side
by side, with standoffs under the mount holes, a cutout for every port,
a ridge where the halves meet and snap joins on the long walls.

Pure: no I/O beyond reading the vendored generator -- just text. Tests
verify the emitted parameters carry every input dimension and that
boards without an `enclosure:` block raise cleanly.
"""
