"""Parametric OpenSCAD enclosure, built on YAPP_Box.

Reads the board's `enclosure:` metadata (PCB outline, mount holes,
ports) and emits a self-contained `.scad` file: the studio's tunables,
the pinned YAPP_Box generator (MIT, vendored in `yapp/`), and the YAPP
parameters derived from both. YAPP lays out the base and the lid side
by side, with standoffs under the mount holes, a cutout for every port,
a ridge where the halves meet and snap joins on the long walls.

Pure: no I/O beyond reading the vendored generator -- just text. Tests
verify the emitted parameters carry every input dimension and that
boards without an `enclosure:` block raise cleanly.
"""
from __future__ import annotations

from functools import lru_cache
from pathlib import Path

from wirestudio.library import BoardEnclosure, BoardPort, Library, MountHole
from wirestudio.model import Design

YAPP_DIR = Path(__file__).parent / "yapp"
YAPP_REF = "f9400c419ef1dea7dc0b3607876989b4f3faa2b7"

# Board edge -> YAPP face. YAPP's X axis runs back to front along the
# PCB length, Y left to right along its width.
_FACES = {"short_a": "cutoutsBack", "short_b": "cutoutsFront",
          "long_a": "cutoutsLeft", "long_b": "cutoutsRight"}


@lru_cache(maxsize=1)
def yapp_generator() -> str:
    return (YAPP_DIR / "YAPPgenerator_v3.scad").read_text()


_HEADER = """\
// Generated by wirestudio for design: {design_id}
// Board: {board_name}
//
// A YAPP_Box enclosure: the tunables below feed the YAPP parameters at
// the end of the file. Tweak them and re-render in OpenSCAD (F5 / F6).
// YAPP_Box generator {yapp_version} by Willem Aandewiel, MIT licence,
// https://github.com/mrWheel/YAPP_Box (commit {yapp_ref}), inlined.

// === Tunables ===
wall = 2.0;            // wall thickness (mm)
floor = 2.0;           // base plane thickness (mm)
lid_t = 2.0;           // lid plane thickness (mm)
clearance = 0.6;       // air gap between PCB edge and inner wall
standoff_h = 4.0;      // PCB sits this far above the base
standoff_d = 5.0;      // standoff outer diameter
standoff_hole = 2.5;   // hole through the standoff (M2.5 clearance)
port_clearance = 0.5;  // extra mm around each port cutout
component_h = {component_h};      // tallest part above the PCB top surface
ridge_h = 4.0;         // depth of the ridge where base and lid meet

// === Board geometry (mm, from library) ===
board_l = {board_l};
board_w = {board_w};
board_t = {board_t};

// === Derived ===
// The lid's walls are at least the ridge plus 2 mm; the base takes the
// rest of the height the PCB and its tallest part need, plus 1 mm.
// YAPP's snap joins need a ridge of at least 1.8 walls.
ridge = max(ridge_h, 1.8 * wall);
lid_wall_h = max(ridge + 2, (component_h + 1) / 2);
base_wall_h = standoff_h + board_t + component_h + 1 - lid_wall_h;
shell_l = board_l + 2*clearance + 2*wall;
"""

_PARAMETERS = """\

// === YAPP parameters ===
// OpenSCAD evaluates a reassigned variable where it was first assigned,
// inside the generator above, so these read only the tunables.
printBaseShell = true;
printLidShell = true;
printSwitchExtenders = false;
printDisplayClips = false;
showSideBySide = true;

pcbLength = board_l;
pcbWidth = board_w;
pcbThickness = board_t;
standoffHeight = standoff_h;
standoffDiameter = standoff_d;
standoffPinDiameter = standoff_hole;
standoffHoleSlack = 0.4;
pcb = [["Main", board_l, board_w, 0, 0, board_t,
        standoff_h, standoff_d, standoff_hole, 0.4]];

paddingFront = clearance;
paddingBack = clearance;
paddingLeft = clearance;
paddingRight = clearance;
wallThickness = wall;
basePlaneThickness = floor;
lidPlaneThickness = lid_t;
ridgeHeight = ridge;
ridgeSlack = 0.3;
roundRadius = 1.0;
lidWallHeight = lid_wall_h;
baseWallHeight = base_wall_h;

pcbStands = [
{stands}
];

cutoutsBack = [
{cutouts_back}
];
cutoutsFront = [
{cutouts_front}
];
cutoutsLeft = [
{cutouts_left}
];
cutoutsRight = [
{cutouts_right}
];

snapJoins = [
  [shell_l/2, 5, yappLeft, yappRight, yappCenter]
];

YAPPgenerate();
"""


def _stand_rows(holes: list[MountHole]) -> str:
    if not holes:
        return "  // No mount holes; the PCB will need to be glued or clipped."
    return ",\n".join(f"  [{h.x_mm}, {h.y_mm}, yappBaseOnly, yappHole, yappNoFillet]" for h in holes)


def _cutout_rows(ports: list[BoardPort]) -> dict[str, str]:
    """Each port is a rectangle centred on it, in YAPP's PCB coordinates:
    along the wall from the PCB origin, and up from the PCB's top."""
    rows: dict[str, list[str]] = {face: [] for face in _FACES.values()}
    for p in ports:
        face = _FACES.get(p.edge)
        if face is None:
            continue
        rows[face].append(
            f"  // {p.kind}\n"
            f"  [{p.offset_mm} + {p.width_mm}/2, {p.height_above_pcb_mm}, "
            f"{p.width_mm} + 2*port_clearance, {p.height_mm} + 2*port_clearance, 0, "
            f"yappRectangle, yappCenter, yappCoordPCB]"
        )
    return {face: ",\n".join(r) if r else "  // none" for face, r in rows.items()}


class EnclosureUnavailable(ValueError):
    """Raised when the design's board lacks `enclosure:` metadata, so
    the parametric generator can't run. Modules that plug into a host
    PCB (ESP-01S, etc.) intentionally skip the block."""


def generate_scad(design: Design, library: Library) -> str:
    """Render the YAPP_Box enclosure for the design's board: base and
    lid, standoffs under the mount holes, a cutout for every port.
    Tunables (wall thickness, clearance, standoff geometry) sit at the
    top of the output as plain OpenSCAD assignments so the user, or
    `openscad -D`, can adjust fit without re-rendering from the studio.
    """
    board_lib_id = design.board.library_id
    board = library.board(board_lib_id)
    encl: BoardEnclosure | None = board.enclosure
    if encl is None:
        raise EnclosureUnavailable(
            f"board '{board_lib_id}' has no enclosure metadata; "
            f"the parametric generator can't produce a shell. "
            f"Modules without a clear PCB outline (ESP-01S etc.) are intentional."
        )

    generator = yapp_generator()
    version = generator.split('Version="', 1)[1].split('"', 1)[0]
    header = _HEADER.format(
        design_id=design.id,
        board_name=board.name,
        yapp_version=version,
        yapp_ref=YAPP_REF[:12],
        component_h=encl.component_height_max_mm,
        board_l=encl.pcb.length_mm,
        board_w=encl.pcb.width_mm,
        board_t=encl.pcb.thickness_mm,
    )
    cutouts = _cutout_rows(encl.ports)
    params = _PARAMETERS.format(
        stands=_stand_rows(encl.mount_holes),
        cutouts_back=cutouts["cutoutsBack"],
        cutouts_front=cutouts["cutoutsFront"],
        cutouts_left=cutouts["cutoutsLeft"],
        cutouts_right=cutouts["cutoutsRight"],
    )
    # The generator assigns its own defaults; the parameters come after
    # it so OpenSCAD's last assignment, ours, wins.
    return header + "\n// === YAPP_Box generator ===\n" + generator + params
