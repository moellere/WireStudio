# Board edge -> YAPP face. YAPP's X axis runs back to front along the
# PCB length, Y left to right along its width.
_FACES = {"short_a": "cutoutsBack", "short_b": "cutoutsFront",
          "long_a": "cutoutsLeft", "long_b": "cutoutsRight"}


@lru_cache(maxsize=1)
def yapp_generator() -> str:
    return (YAPP_DIR / "YAPPgenerator_v3.scad").read_text()


